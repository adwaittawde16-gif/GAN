def segment_plant(img: Image.Image, size=(256, 256)) -> tuple:
    """Returns (plant_rgba, alpha_mask) — segmented with GrabCut on original"""
    img = img.convert("RGB").resize(size)
    arr = np.array(img)
    bgr = cv2.cvtColor(arr, cv2.COLOR_RGB2BGR)

    mask = np.zeros(bgr.shape[:2], np.uint8)
    fg_model = np.zeros((1, 65), np.float64)
    bg_model = np.zeros((1, 65), np.float64)
    rect = (8, 8, bgr.shape[1] - 8, bgr.shape[0] - 8)

    try:
        cv2.grabCut(bgr, mask, rect, bg_model, fg_model, 8, cv2.GC_INIT_WITH_RECT)
        alpha = np.where((mask == 2) | (mask == 0), 0, 255).astype(np.uint8)
        # Smooth edges
        alpha = cv2.GaussianBlur(alpha, (7, 7), 0)
        # Dilate slightly to avoid losing plant edges
        kernel = np.ones((3, 3), np.uint8)
        alpha = cv2.dilate(alpha, kernel, iterations=1)
    except:
        # Fallback: no segmentation
        alpha = np.full(bgr.shape[:2], 255, np.uint8)

    return arr, alpha


def make_snow_bg(size=(256, 256)) -> np.ndarray:
    """Procedural snow texture"""
    bg = np.full((*size, 3), [235, 242, 255], dtype=np.float32)
    # Large snow variations
    noise = np.random.normal(0, 15, (*size, 3))
    bg = np.clip(bg + noise, 200, 255)
    # Random snowflakes
    num_flakes = np.random.randint(80, 160)
    for _ in range(num_flakes):
        x, y = np.random.randint(0, size[1]), np.random.randint(0, size[0])
        r = np.random.randint(1, 4)
        cv2.circle(bg.astype(np.uint8), (x, y), r, (255, 255, 255), -1)
    return np.clip(bg, 0, 255).astype(np.uint8)


def make_sand_bg(size=(256, 256)) -> np.ndarray:
    """Procedural sand texture"""
    bg = np.full((*size, 3), [194, 162, 105], dtype=np.float32)
    # Sand grain noise
    noise = np.random.normal(0, 20, (*size, 3))
    bg = np.clip(bg + noise, 0, 255)
    # Subtle dune ripples using sin
    for i in range(size[0]):
        wave = int(8 * np.sin(i / 15.0))
        bg[i, :, 0] = np.clip(bg[i, :, 0] + wave, 0, 255)
        bg[i, :, 1] = np.clip(bg[i, :, 1] + wave * 0.7, 0, 255)
    return bg.astype(np.uint8)


def make_white_bg(size=(256, 256)) -> np.ndarray:
    """Clean white background for no-BG look"""
    bg = np.full((*size, 3), [245, 245, 245], dtype=np.uint8)
    return bg


def composite(plant_arr, alpha, bg_arr) -> Image.Image:
    """Blend plant onto background using alpha mask"""
    plant  = plant_arr.astype(np.float32)
    bg     = bg_arr.astype(np.float32)
    a      = alpha.astype(np.float32) / 255.0
    a3     = np.stack([a, a, a], axis=-1)
    result = (plant * a3 + bg * (1 - a3)).astype(np.uint8)
    return Image.fromarray(result)


