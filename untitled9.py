def apply_snow_scene(img: Image.Image, size=(256, 256)) -> Image.Image:
    """Cool blue tint + snow particles overlaid on full image"""
    img = img.convert("RGB").resize(size)

    # Cool desaturated tint
    img = ImageEnhance.Color(img).enhance(0.65)
    img = ImageEnhance.Brightness(img).enhance(1.1)

    arr = np.array(img, dtype=np.float32)

    # Blue-white color cast
    arr[:, :, 0] = np.clip(arr[:, :, 0] * 0.85, 0, 255)  # reduce red
    arr[:, :, 2] = np.clip(arr[:, :, 2] * 1.25, 0, 255)  # boost blue

    # Snow drift at bottom 25%
    h = size[0]
    snow_start = int(h * 0.75)
    snow_layer = np.full((h - snow_start, size[1], 3), [230, 238, 255], dtype=np.float32)
    blend = np.linspace(0, 0.85, h - snow_start)[:, np.newaxis, np.newaxis]
    arr[snow_start:] = arr[snow_start:] * (1 - blend) + snow_layer * blend

    # Falling snowflake dots
    for _ in range(300):
        x = np.random.randint(0, size[1])
        y = np.random.randint(0, size[0])
        r = np.random.randint(1, 4)
        alpha_flake = np.random.uniform(0.5, 0.95)
        y0, y1 = max(0, y-r), min(size[0], y+r)
        x0, x1 = max(0, x-r), min(size[1], x+r)
        arr[y0:y1, x0:x1] = arr[y0:y1, x0:x1] * (1 - alpha_flake) + np.array([255, 255, 255]) * alpha_flake

    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def apply_sand_scene(img: Image.Image, size=(256, 256)) -> Image.Image:
    """Warm desert tint + sandy ground overlay at bottom"""
    img = img.convert("RGB").resize(size)

    # Warm, high-contrast tint
    img = ImageEnhance.Color(img).enhance(0.9)
    img = ImageEnhance.Brightness(img).enhance(1.15)
    img = ImageEnhance.Contrast(img).enhance(1.1)

    arr = np.array(img, dtype=np.float32)

    # Warm color cast across whole image
    arr[:, :, 0] = np.clip(arr[:, :, 0] * 1.12, 0, 255)   # boost red
    arr[:, :, 1] = np.clip(arr[:, :, 1] * 1.05, 0, 255)   # slight green boost
    arr[:, :, 2] = np.clip(arr[:, :, 2] * 0.75, 0, 255)   # cut blue

    # Sandy ground at bottom 30%
    h = size[0]
    sand_start = int(h * 0.70)
    sand_layer = np.random.normal(0, 18, (h - sand_start, size[1], 3))
    sand_base = np.full((h - sand_start, size[1], 3), [210, 170, 95], dtype=np.float32)
    sand_tex = np.clip(sand_base + sand_layer, 0, 255)

    blend = np.linspace(0, 0.9, h - sand_start)[:, np.newaxis, np.newaxis]
    arr[sand_start:] = arr[sand_start:] * (1 - blend) + sand_tex * blend

    # Heat shimmer — slight blur on top third
    top = Image.fromarray(arr[:int(h*0.35)].astype(np.uint8))
    top = top.filter(ImageFilter.GaussianBlur(radius=1))
    arr[:int(h*0.35)] = np.array(top, dtype=np.float32)

    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def apply_clean_scene(img: Image.Image, size=(256, 256)) -> Image.Image:
    """Studio-clean: bright, sharp, soft vignette edges"""
    img = img.convert("RGB").resize(size)
    img = ImageEnhance.Brightness(img).enhance(1.2)
    img = ImageEnhance.Contrast(img).enhance(1.1)
    img = ImageEnhance.Sharpness(img).enhance(1.3)

    arr = np.array(img, dtype=np.float32)

    # Soft white vignette at edges
    h, w = arr.shape[:2]
    Y, X = np.ogrid[:h, :w]
    cx, cy = w / 2, h / 2
    dist = np.sqrt(((X - cx) / cx) ** 2 + ((Y - cy) / cy) ** 2)
    vignette = np.clip(dist - 0.6, 0, 1) * 2.0
    vignette = np.stack([vignette] * 3, axis=-1)
    arr = arr * (1 - vignette) + 255 * vignette

    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


