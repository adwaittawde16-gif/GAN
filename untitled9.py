def apply_lighting(img: Image.Image, condition: str) -> Image.Image:
    img = img.convert("RGB")
    if condition == "bright":
        img = ImageEnhance.Brightness(img).enhance(1.6)
        img = ImageEnhance.Contrast(img).enhance(0.85)
        # simulate glare wash
        overlay = Image.new("RGB", img.size, (255, 255, 220))
        img = Image.blend(img, overlay, alpha=0.18)
    elif condition == "dim":
        img = ImageEnhance.Brightness(img).enhance(0.55)
        img = ImageEnhance.Contrast(img).enhance(1.1)
        img = ImageEnhance.Color(img).enhance(0.75)
    elif condition == "dark":
        img = ImageEnhance.Brightness(img).enhance(0.28)
        img = ImageEnhance.Contrast(img).enhance(1.2)
        # add ISO noise
        arr = np.array(img, dtype=np.float32)
        noise = np.random.normal(0, 12, arr.shape)
        arr = np.clip(arr + noise, 0, 255).astype(np.uint8)
        img = Image.fromarray(arr)
    return img


def apply_background(img: Image.Image, bg_color: tuple, size=(256, 256)) -> Image.Image:
    img = img.resize(size)
    # GrabCut segmentation
    arr = np.array(img)
    bgr = cv2.cvtColor(arr, cv2.COLOR_RGB2BGR)
    mask = np.zeros(bgr.shape[:2], np.uint8)
    rect = (10, 10, bgr.shape[1] - 10, bgr.shape[0] - 10)
    fg_model = np.zeros((1, 65), np.float64)
    bg_model = np.zeros((1, 65), np.float64)
    try:
        cv2.grabCut(bgr, mask, rect, bg_model, fg_model, 5, cv2.GC_INIT_WITH_RECT)
        fg_mask = np.where((mask == 2) | (mask == 0), 0, 1).astype(np.uint8)
        fg_mask = cv2.GaussianBlur(fg_mask * 255, (5, 5), 0)
        alpha = fg_mask.astype(np.float32) / 255.0
    except:
        alpha = np.ones(bgr.shape[:2], np.float32)

    # Add texture variation to background
    bg = np.full((*size[::-1], 3), bg_color, dtype=np.float32)
    noise = np.random.normal(0, 15, bg.shape)
    bg = np.clip(bg + noise, 0, 255).astype(np.uint8)
    bg_img = Image.fromarray(bg)

    # Composite
    plant = np.array(img).astype(np.float32)
    background = np.array(bg_img).astype(np.float32)
    alpha3 = np.stack([alpha] * 3, axis=-1)
    composited = (plant * alpha3 + background * (1 - alpha3)).astype(np.uint8)
    return Image.fromarray(composited)


