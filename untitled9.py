def fetch_inaturalist(species_name, folder, max_images=15):
    """iNaturalist: Field photographs by botanists & researchers"""
    endpoint = "https://api.inaturalist.org/v1/observations"
    params = {
        "taxon_name": species_name,
        "quality_grade": "research",
        "photos": "true",
        "per_page": max_images,
        "order_by": "votes"
    }
    try:
        data = requests.get(endpoint, params=params, headers=HEADERS, timeout=20).json()
    except Exception as e:
        print(f"  iNaturalist error for {species_name}: {e}")
        return 0

    count = 0
    for obs in data.get("results", []):
        for photo in obs.get("photos", []):
            url = photo.get("url", "").replace("square", "large")
            if not url:
                continue
            try:
                resp = requests.get(url, headers=HEADERS, timeout=12)
                img = Image.open(BytesIO(resp.content)).convert("RGB")
                img.thumbnail((512, 512), Image.Resampling.LANCZOS)
                img.save(f"{folder}/inat_{count:03d}.jpg", quality=92)
                count += 1
                if count >= max_images:
                    return count
            except Exception:
                continue
    return count

def fetch_gbif(species_name, folder, max_images=13):
    """GBIF: Digitized herbarium voucher specimens — high botanical accuracy"""
    # Step 1: Get GBIF species key
    try:
        match_resp = requests.get(
            "https://api.gbif.org/v1/species/match",
            params={"name": species_name},
            timeout=15
        ).json()
        species_key = match_resp.get("usageKey")
        if not species_key:
            return 0
    except Exception as e:
        print(f"  GBIF species lookup failed for {species_name}: {e}")
        return 0

    # Step 2: Fetch occurrence records with media
    try:
        occ_resp = requests.get(
            "https://api.gbif.org/v1/occurrence/search",
            params={
                "taxonKey": species_key,
                "mediaType": "StillImage",
                "limit": max_images * 3,
                "hasCoordinate": "true"
            },
            timeout=20
        ).json()
    except Exception as e:
        print(f"  GBIF occurrence error for {species_name}: {e}")
        return 0

    count = 0
    for record in occ_resp.get("results", []):
        for media in record.get("media", []):
            url = media.get("identifier", "")
            if not url or not url.lower().endswith(('.jpg', '.jpeg', '.png')):
                continue
            try:
                resp = requests.get(url, headers=HEADERS, timeout=12)
                img = Image.open(BytesIO(resp.content)).convert("RGB")
                img.thumbnail((512, 512), Image.Resampling.LANCZOS)
                img.save(f"{folder}/gbif_{count:03d}.jpg", quality=92)
                count += 1
                if count >= max_images:
                    return count
            except Exception:
                continue

    return count

