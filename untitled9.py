def apply_weather(img: Image.Image, season: str) -> Image.Image:
    img = img.convert("RGB").resize((256, 256))
    arr = np.array(img, dtype=np.float32)

    if season == "summer":
        # Warm, bright, slight yellow haze
        img = ImageEnhance.Brightness(img).enhance(1.5)
        img = ImageEnhance.Contrast(img).enhance(0.9)
        img = ImageEnhance.Color(img).enhance(1.2)
        arr = np.array(img, dtype=np.float32)
        arr[:, :, 0] = np.clip(arr[:, :, 0] * 1.08, 0, 255)  # boost red
        arr[:, :, 2] = np.clip(arr[:, :, 2] * 0.88, 0, 255)  # reduce blue
        # heat haze overlay
        haze = np.random.normal(0, 5, arr.shape)
        arr = np.clip(arr + haze, 0, 255)

    elif season == "winter":
        # Cool, desaturated, blue-gray tint, slight fog
        img = ImageEnhance.Brightness(img).enhance(0.85)
        img = ImageEnhance.Color(img).enhance(0.55)
        arr = np.array(img, dtype=np.float32)
        arr[:, :, 2] = np.clip(arr[:, :, 2] * 1.15, 0, 255)  # boost blue
        arr[:, :, 0] = np.clip(arr[:, :, 0] * 0.90, 0, 255)  # reduce red
        # frost fog: blend with white
        fog = np.full_like(arr, 210)
        arr = arr * 0.78 + fog * 0.22

    elif season == "monsoon":
        # Dark, heavy greens, wet look, rain streaks
        img = ImageEnhance.Brightness(img).enhance(0.65)
        img = ImageEnhance.Color(img).enhance(1.35)
        img = ImageEnhance.Contrast(img).enhance(1.15)
        arr = np.array(img, dtype=np.float32)
        arr[:, :, 1] = np.clip(arr[:, :, 1] * 1.1, 0, 255)  # boost green
        arr[:, :, 2] = np.clip(arr[:, :, 2] * 1.1, 0, 255)  # boost blue
        # rain streaks
        num_streaks = 120
        for _ in range(num_streaks):
            x = np.random.randint(0, 256)
            y_start = np.random.randint(0, 220)
            length = np.random.randint(8, 22)
            alpha = np.random.uniform(0.25, 0.55)
            for dy in range(length):
                if y_start + dy < 256:
                    arr[y_start + dy, x] = arr[y_start + dy, x] * (1 - alpha) + 200 * alpha

    elif season == "autumn":
        # Warm orange-brown tones, reduced green, slightly dim
        img = ImageEnhance.Brightness(img).enhance(0.95)
        img = ImageEnhance.Color(img).enhance(1.1)
        arr = np.array(img, dtype=np.float32)
        arr[:, :, 0] = np.clip(arr[:, :, 0] * 1.18, 0, 255)  # boost red
        arr[:, :, 1] = np.clip(arr[:, :, 1] * 0.88, 0, 255)  # reduce green
        arr[:, :, 2] = np.clip(arr[:, :, 2] * 0.75, 0, 255)  # reduce blue

    elif season == "spring":
        # Fresh, vibrant greens, soft warm light
        img = ImageEnhance.Brightness(img).enhance(1.15)
        img = ImageEnhance.Color(img).enhance(1.3)
        img = ImageEnhance.Contrast(img).enhance(0.95)
        arr = np.array(img, dtype=np.float32)
        arr[:, :, 1] = np.clip(arr[:, :, 1] * 1.12, 0, 255)  # boost green
        arr[:, :, 0] = np.clip(arr[:, :, 0] * 1.05, 0, 255)  # slight warm

    return Image.fromarray(arr.astype(np.uint8))


