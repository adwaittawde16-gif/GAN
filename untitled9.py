def segment_plant_v2(img_pil, size=(256, 256)):
    """Cleaner segmentation with morphological cleanup + noise removal"""
    img = img_pil.convert("RGB").resize(size)
    arr = np.array(img)
    bgr = cv2.cvtColor(arr, cv2.COLOR_RGB2BGR)

    h, w = bgr.shape[:2]
    margin = int(min(h, w) * 0.06)
    rect = (margin, margin, w - 2 * margin, h - 2 * margin)

    mask = np.zeros((h, w), np.uint8)
    fg_model = np.zeros((1, 65), np.float64)
    bg_model = np.zeros((1, 65), np.float64)

    try:
        cv2.grabCut(bgr, mask, rect, bg_model, fg_model, 10, cv2.GC_INIT_WITH_RECT)
        alpha = np.where((mask == 2) | (mask == 0), 0, 255).astype(np.uint8)

        # Close holes inside plant
        kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))
        alpha = cv2.morphologyEx(alpha, cv2.MORPH_CLOSE, kernel, iterations=4)
        alpha = cv2.morphologyEx(alpha, cv2.MORPH_OPEN, kernel, iterations=1)

        # Remove small scattered noise blobs
        num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(alpha, 8)
        min_area = h * w * 0.008  # ignore blobs < 0.8% of image
        clean = np.zeros_like(alpha)
        for lbl in range(1, num_labels):
            if stats[lbl, cv2.CC_STAT_AREA] > min_area:
                clean[labels == lbl] = 255
        alpha = clean

    except Exception:
        alpha = np.full((h, w), 255, np.uint8)

    # Smooth edges
    alpha = cv2.GaussianBlur(alpha, (13, 13), 0)
    return arr, alpha


