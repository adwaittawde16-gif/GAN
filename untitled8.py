def render_bright_sunlight(img_rgb):
    """Simulates direct sunlight, specular highlights, and harsh shadows"""
    arr = img_rgb.astype(np.float32) / 255.0
    bright = np.power(arr, 0.78) * 1.30
    h, w, _ = arr.shape
    glare = np.zeros((h, w), dtype=np.float32)
    cv2.circle(glare, (int(w * 0.35), int(h * 0.25)), int(min(h, w) * 0.35), 0.22, -1)
    glare = cv2.GaussianBlur(glare, (101, 101), 0)
    for c in range(3):
        bright[:, :, c] += glare
    return np.clip(bright * 255.0, 0, 255).astype(np.uint8)

def render_dim_canopy(img_rgb):
    """Simulates canopy twilight, overcast shade, and muted contrast"""
    arr = img_rgb.astype(np.float32) / 255.0
    dim = np.power(arr, 1.35) * 0.68
    dim[:, :, 0] *= 0.88  # Red reduction
    dim[:, :, 1] *= 0.95  # Neutral foliage green
    dim[:, :, 2] *= 1.08  # Atmospheric cool blue tint
    return np.clip(dim * 255.0, 0, 255).astype(np.uint8)

def render_dark_flash(img_rgb):
    """Simulates night field capture with mobile LED flash falloff & sensor grain"""
    h, w, _ = img_rgb.shape
    arr = img_rgb.astype(np.float32) / 255.0
    ambient = arr * 0.10  # Pitch black baseline

    Y, X = np.ogrid[:h, :w]
    cy, cx = h // 2, w // 2
    dist = np.sqrt((X - cx)**2 + (Y - cy)**2)
    max_r = np.sqrt(cx**2 + cy**2)
    flash = np.clip(1.0 - (dist / (max_r * 0.75)), 0.0, 1.0) ** 1.9

    illuminated = ambient + (arr * 1.35 * flash[:, :, np.newaxis])
    noise = np.random.normal(0, 0.035, (h, w, 3))  # Sensor noise
    illuminated += noise
    return np.clip(illuminated * 255.0, 0, 255).astype(np.uint8)

