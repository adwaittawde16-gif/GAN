def render_dark_flash(img_rgb):
    h, w, _ = img_rgb.shape
    arr = img_rgb.astype(np.float32) / 255.0
    ambient = arr * 0.10
    Y, X = np.ogrid[:h, :w]
    cy, cx = h // 2, w // 2
    dist = np.sqrt((X - cx)**2 + (Y - cy)**2)
    max_r = np.sqrt(cx**2 + cy**2)
