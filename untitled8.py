def apply_bright(img_np):
    """Harsh solar bloom & specular reflection"""
    arr = img_np.astype(np.float32) / 255.0
    bright = np.power(arr, 0.75) * 1.25
    return np.clip(bright * 255.0, 0, 255).astype(np.uint8)

def apply_dim(img_np):
    """Canopy twilight with cool ambient shadow"""
    arr = img_np.astype(np.float32) / 255.0
    dim = np.power(arr, 1.3) * 0.70
    dim[:, :, 0] *= 0.90 # Cool tint
    dim[:, :, 2] *= 1.05
    return np.clip(dim * 255.0, 0, 255).astype(np.uint8)

def apply_dark_flash(img_np):
    """Night field capture with phone flash falloff and ISO noise"""
    h, w, _ = img_np.shape
    arr = img_np.astype(np.float32) / 255.0
    Y, X = np.ogrid[:h, :w]
    cy, cx = h // 2, w // 2
    dist = np.sqrt((X - cx)**2 + (Y - cy)**2)
    flash = np.clip(1.0 - (dist / (np.sqrt(cx**2 + cy**2) * 0.75)), 0.0, 1.0) ** 1.8
    scene = (arr * 0.15) + (arr * 1.2 * flash[:, :, np.newaxis])
    scene += np.random.normal(0, 0.035, (h, w, 3))
    return np.clip(scene * 255.0, 0, 255).astype(np.uint8)

