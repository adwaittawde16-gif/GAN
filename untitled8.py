# Cell 4: Train on GPU with Mode-Seeking & EMA (60 Epochs)
LATENT_DIM = 128

G = ResNetGenerator(latent_dim=LATENT_DIM).to(device)
D = ResNetDiscriminator().to(device)
G_ema = copy.deepcopy(G).eval().requires_grad_(False)

opt_G = optim.Adam(G.parameters(), lr=0.0001, betas=(0.0, 0.9))
opt_D = optim.Adam(D.parameters(), lr=0.0004, betas=(0.0, 0.9))

EPOCHS = 60
print(f"Training on {torch.cuda.get_device_name(0)} for {EPOCHS} epochs...")

for epoch in range(EPOCHS):
    d_loss_epoch, g_loss_epoch = 0.0, 0.0

    for real_imgs, labels in train_loader:
        real_imgs, labels = real_imgs.to(device), labels.to(device)
        B = real_imgs.size(0)

        # 1. Discriminator Step
        opt_D.zero_grad()
        z1 = torch.randn(B, LATENT_DIM, device=device)
        fake_imgs = G(z1, labels)

        d_real = D(diff_augment(real_imgs), labels)
        d_fake = D(diff_augment(fake_imgs.detach()), labels)

        loss_D = torch.mean(F.relu(1.0 - d_real)) + torch.mean(F.relu(1.0 + d_fake))
        loss_D.backward()
        opt_D.step()

        # 2. Generator Step + Mode-Seeking Loss
        opt_G.zero_grad()
        z2 = torch.randn(B, LATENT_DIM, device=device)
        fake_1 = G(z1, labels)
        fake_2 = G(z2, labels)

        adv_loss = -torch.mean(D(diff_augment(fake_1), labels))

        # Diversity loss: forces z1 and z2 to yield distinct leaf/fruit structures
        div_loss = -1.2 * (torch.mean(torch.abs(fake_1 - fake_2)) / (torch.mean(torch.abs(z1 - z2)) + 1e-5))

        loss_G = adv_loss + div_loss
        loss_G.backward()
        opt_G.step()

        # Update EMA weights
        with torch.no_grad():
            for p_ema, p in zip(G_ema.parameters(), G.parameters()):
                p_ema.data.mul_(0.999).add_(p.data, alpha=0.001)

        d_loss_epoch += loss_D.item()
        g_loss_epoch += adv_loss.item()

    if (epoch + 1) % 10 == 0 or epoch == 0:
        d_avg = d_loss_epoch / len(train_loader)
        g_avg = g_loss_epoch / len(train_loader)
        print(f"Epoch [{epoch+1:02d}/{EPOCHS}] | D Loss: {d_avg:.3f} | G Loss: {g_avg:.3f}")

torch.save(G_ema.state_dict(), f"{DIRS['checkpoints']}/sarpagandha_hd_ema.pth")
