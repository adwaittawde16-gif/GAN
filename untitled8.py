# --- 1. U-Net Generator with Skip Connections ---
class UNetDown(nn.Module):
    def __init__(self, in_c, out_c, normalize=True):
        super().__init__()
        layers = [nn.Conv2d(in_c, out_c, 4, 2, 1, bias=False)]
        if normalize:
            layers.append(nn.BatchNorm2d(out_c))
        layers.append(nn.LeakyReLU(0.2, inplace=False))
        self.model = nn.Sequential(*layers)

    def forward(self, x):
        return self.model(x)

class UNetUp(nn.Module):
    def __init__(self, in_c, out_c, dropout=0.0):
        super().__init__()
        layers = [
            nn.ConvTranspose2d(in_c, out_c, 4, 2, 1, bias=False),
            nn.BatchNorm2d(out_c),
            nn.ReLU(inplace=False)
        ]
        if dropout:
            layers.append(nn.Dropout(dropout))
        self.model = nn.Sequential(*layers)

    def forward(self, x, skip_input):
        x = self.model(x)
        return torch.cat((x, skip_input), 1)

class RelightingGenerator(nn.Module):
    """Conditional U-Net: Preserves flower anatomy via skip connections while modifying lighting"""
    def __init__(self, num_conditions=3):
        super().__init__()
        # Input: 3 channels (RGB) + 3 channels (Condition One-Hot Mask) = 6 channels
        self.cond_emb = nn.Embedding(num_conditions, 256 * 256)

        self.down1 = UNetDown(3 + 1, 64, normalize=False) # 256 -> 128
        self.down2 = UNetDown(64, 128)                   # 128 -> 64
        self.down3 = UNetDown(128, 256)                  # 64 -> 32
        self.down4 = UNetDown(256, 512)                  # 32 -> 16
        self.down5 = UNetDown(512, 512)                  # 16 -> 8
        self.down6 = UNetDown(512, 512)                  # 8 -> 4

        self.up1 = UNetUp(512, 512, dropout=0.2)         # 4 -> 8
        self.up2 = UNetUp(1024, 512)                     # 8 -> 16
        self.up3 = UNetUp(1024, 256)                     # 16 -> 32
        self.up4 = UNetUp(512, 128)                      # 32 -> 64
        self.up5 = UNetUp(256, 64)                       # 64 -> 128

        self.final = nn.Sequential(
            nn.ConvTranspose2d(128, 3, 4, 2, 1),         # 128 -> 256
            nn.Tanh()
        )

    def forward(self, x, condition):
        # Broadcast condition label over spatial dimensions
        cond_map = self.cond_emb(condition).view(x.size(0), 1, 256, 256)
        x_cond = torch.cat([x, cond_map], dim=1)

        d1 = self.down1(x_cond)
        d2 = self.down2(d1)
        d3 = self.down3(d2)
        d4 = self.down4(d3)
        d5 = self.down5(d4)
        d6 = self.down6(d5)

        u1 = self.up1(d6, d5)
        u2 = self.up2(u1, d4)
        u3 = self.up3(u2, d3)
        u4 = self.up4(u3, d2)
        u5 = self.up5(u4, d1)

        return self.final(u5)

# --- 2. 70x70 PatchGAN Discriminator ---
class PatchGANDiscriminator(nn.Module):
    """Evaluates realism at 70x70 local patches to force crisp details"""
    def __init__(self):
        super().__init__()
        self.model = nn.Sequential(
            nn.Conv2d(3 + 3, 64, 4, 2, 1), # Input: original + target image (6 channels)
            nn.LeakyReLU(0.2, inplace=False),

            nn.Conv2d(64, 128, 4, 2, 1),
            nn.BatchNorm2d(128),
            nn.LeakyReLU(0.2, inplace=False),

            nn.Conv2d(128, 256, 4, 2, 1),
            nn.BatchNorm2d(256),
            nn.LeakyReLU(0.2, inplace=False),

            nn.Conv2d(256, 512, 4, 1, 1),
            nn.BatchNorm2d(512),
            nn.LeakyReLU(0.2, inplace=False),

            nn.Conv2d(512, 1, 4, 1, 1) # Patch output
        )

    def forward(self, img_A, img_B):
        # Concatenate real/generated image with the source image
        img_input = torch.cat((img_A, img_B), 1)
        return self.model(img_input)

