# --- Harmonization Generator ---
class HarmonizationGenerator(nn.Module):
    """Fuses foreground plant + background plate + lighting conditions"""
    def __init__(self, num_lights=3):
        super().__init__()
        # Input: 3 channels (Plant + Mask) + 3 channels (Background Plate) + 1 channel (Light condition) = 7 channels
        self.light_emb = nn.Embedding(num_lights, 256 * 256)

        # U-Net Down
        self.d1 = nn.Sequential(nn.Conv2d(7, 64, 4, 2, 1), nn.LeakyReLU(0.2, False))
        self.d2 = nn.Sequential(nn.Conv2d(64, 128, 4, 2, 1), nn.BatchNorm2d(128), nn.LeakyReLU(0.2, False))
        self.d3 = nn.Sequential(nn.Conv2d(128, 256, 4, 2, 1), nn.BatchNorm2d(256), nn.LeakyReLU(0.2, False))
        self.d4 = nn.Sequential(nn.Conv2d(256, 512, 4, 2, 1), nn.BatchNorm2d(512), nn.LeakyReLU(0.2, False))
        self.d5 = nn.Sequential(nn.Conv2d(512, 512, 4, 2, 1), nn.BatchNorm2d(512), nn.LeakyReLU(0.2, False))

        # U-Net Up with Skip Connections
        self.u1 = nn.Sequential(nn.ConvTranspose2d(512, 512, 4, 2, 1), nn.BatchNorm2d(512), nn.ReLU(False))
        self.u2 = nn.Sequential(nn.ConvTranspose2d(1024, 256, 4, 2, 1), nn.BatchNorm2d(256), nn.ReLU(False))
        self.u3 = nn.Sequential(nn.ConvTranspose2d(512, 128, 4, 2, 1), nn.BatchNorm2d(128), nn.ReLU(False))
        self.u4 = nn.Sequential(nn.ConvTranspose2d(256, 64, 4, 2, 1), nn.BatchNorm2d(64), nn.ReLU(False))

        self.final = nn.Sequential(
            nn.ConvTranspose2d(128, 3, 4, 2, 1),
            nn.Tanh()
        )

    def forward(self, fg, bg, light_idx):
        l_map = self.light_emb(light_idx).view(fg.size(0), 1, 256, 256)
        x = torch.cat([fg, bg, l_map], dim=1) # 7 Channels

        # Encoder
        x1 = self.d1(x)
        x2 = self.d2(x1)
        x3 = self.d3(x2)
        x4 = self.d4(x3)
        x5 = self.d5(x4)

        # Decoder with Skip Connections
        y1 = self.u1(x5)
        y2 = self.u2(torch.cat([y1, x4], 1))
        y3 = self.u3(torch.cat([y2, x3], 1))
        y4 = self.u4(torch.cat([y3, x2], 1))
        out = self.final(torch.cat([y4, x1], 1))
        return out

