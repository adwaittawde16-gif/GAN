def diff_augment(x):
    """Differentiable spatial & color augmentation"""
    # Color
    x = x + (torch.rand(x.size(0), 1, 1, 1, device=x.device) - 0.5) * 0.25
    x = x * (torch.rand(x.size(0), 1, 1, 1, device=x.device) * 0.3 + 0.85)

    # Translation
    shift_x = int(x.size(2) * 0.125 + 0.5)
    shift_y = int(x.size(3) * 0.125 + 0.5)
    tx = torch.randint(-shift_x, shift_x + 1, size=[x.size(0), 1, 1], device=x.device)
    ty = torch.randint(-shift_y, shift_y + 1, size=[x.size(0), 1, 1], device=x.device)

    grid_b, grid_x, grid_y = torch.meshgrid(
        torch.arange(x.size(0), dtype=torch.long, device=x.device),
        torch.arange(x.size(2), dtype=torch.long, device=x.device),
        torch.arange(x.size(3), dtype=torch.long, device=x.device),
        indexing='ij'
    )
    grid_x = torch.clamp(grid_x + tx, 0, x.size(2) - 1)
    grid_y = torch.clamp(grid_y + ty, 0, x.size(3) - 1)

    x = x.permute(0, 2, 3, 1)[grid_b, grid_x, grid_y].permute(0, 3, 1, 2)
    return x

class SelfAttention(nn.Module):
    def __init__(self, in_dim):
        super().__init__()
        self.query = spectral_norm(nn.Conv2d(in_dim, in_dim // 8, 1))
        self.key   = spectral_norm(nn.Conv2d(in_dim, in_dim // 8, 1))
        self.value = spectral_norm(nn.Conv2d(in_dim, in_dim, 1))
        self.gamma = nn.Parameter(torch.zeros(1))

    def forward(self, x):
        B, C, H, W = x.size()
        q = self.query(x).view(B, -1, H * W).permute(0, 2, 1)
        k = self.key(x).view(B, -1, H * W)
        attn = F.softmax(torch.bmm(q, k), dim=-1)
        v = self.value(x).view(B, -1, H * W)
        out = torch.bmm(v, attn.permute(0, 2, 1)).view(B, C, H, W)
        return self.gamma * out + x

class ResBlockUp(nn.Module):
    def __init__(self, in_c, out_c):
        super().__init__()
        self.conv1 = spectral_norm(nn.Conv2d(in_c, out_c, 3, 1, padding=1, padding_mode='reflect'))
        self.conv2 = spectral_norm(nn.Conv2d(out_c, out_c, 3, 1, padding=1, padding_mode='reflect'))
        self.bn1 = nn.BatchNorm2d(in_c)
        self.bn2 = nn.BatchNorm2d(out_c)
        self.shortcut = spectral_norm(nn.Conv2d(in_c, out_c, 1, 1, 0))

    def forward(self, x):
        h_skip = self.shortcut(F.interpolate(x, scale_factor=2, mode='bilinear', align_corners=False))
        h = F.relu(self.bn1(x), inplace=False)
        h = self.conv1(F.interpolate(h, scale_factor=2, mode='bilinear', align_corners=False))
        h = self.conv2(F.relu(self.bn2(h), inplace=False))
        return h + h_skip

class ResBlockDown(nn.Module):
    def __init__(self, in_c, out_c):
        super().__init__()
        self.conv1 = spectral_norm(nn.Conv2d(in_c, out_c, 3, 1, padding=1, padding_mode='reflect'))
        self.conv2 = spectral_norm(nn.Conv2d(out_c, out_c, 3, 1, padding=1, padding_mode='reflect'))
        self.shortcut = spectral_norm(nn.Conv2d(in_c, out_c, 1, 1, 0))

    def forward(self, x):
        h_skip = self.shortcut(F.avg_pool2d(x, 2))
        h = self.conv1(F.leaky_relu(x, 0.2, inplace=False))
        h = F.avg_pool2d(self.conv2(F.leaky_relu(h, 0.2, inplace=False)), 2)
        return h + h_skip

class ResNetGenerator(nn.Module):
    def __init__(self, latent_dim=128, num_classes=3, embed_dim=64):
        super().__init__()
        self.embed = nn.Embedding(num_classes, embed_dim)
        self.fc = nn.Sequential(
            nn.Linear(latent_dim + embed_dim, 512 * 4 * 4),
            nn.BatchNorm1d(512 * 4 * 4),
            nn.ReLU(inplace=False)
        )
        self.res1 = ResBlockUp(512, 256) # 4 -> 8
        self.res2 = ResBlockUp(256, 128) # 8 -> 16
        self.attn = SelfAttention(128)
        self.res3 = ResBlockUp(128, 64)  # 16 -> 32
        self.res4 = ResBlockUp(64, 32)   # 32 -> 64
        self.res5 = ResBlockUp(32, 16)   # 64 -> 128
        self.out = nn.Sequential(
            nn.BatchNorm2d(16),
            nn.ReLU(inplace=False),
            spectral_norm(nn.Conv2d(16, 3, 3, 1, padding=1, padding_mode='reflect')),
            nn.Tanh()
        )

    def forward(self, z, y):
        x = torch.cat([z, self.embed(y)], dim=1)
        x = self.fc(x).view(-1, 512, 4, 4)
        x = self.res1(x)
        x = self.res2(x)
        x = self.attn(x)
        x = self.res3(x)
        x = self.res4(x)
        x = self.res5(x)
        return self.out(x)

class ResNetDiscriminator(nn.Module):
    def __init__(self, num_classes=3):
        super().__init__()
        self.block1 = ResBlockDown(3, 32)   # 128 -> 64
        self.block2 = ResBlockDown(32, 64)  # 64 -> 32
        self.attn = SelfAttention(64)
        self.block3 = ResBlockDown(64, 128) # 32 -> 16
        self.block4 = ResBlockDown(128, 256)# 16 -> 8
        self.block5 = ResBlockDown(256, 512)# 8 -> 4
        self.fc = spectral_norm(nn.Linear(512, 1))
        self.embed = spectral_norm(nn.Embedding(num_classes, 512))

    def forward(self, x, y):
        h = self.block5(self.block4(self.block3(self.attn(self.block2(self.block1(x))))))
        h = torch.sum(F.leaky_relu(h, 0.2, inplace=False), dim=[2, 3])
        return self.fc(h) + torch.sum(self.embed(y) * h, dim=1, keepdim=True)

